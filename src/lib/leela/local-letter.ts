import type { PathLetter } from "@/lib/leela/letter";

function bit(seed: string, name: string) {
  const found = seed.split(". ").find((part) => part.startsWith(`${name}: `));
  return found ? found.slice(name.length + 2).trim() : "";
}

export function localLetter(intention: string, seed: string, channel: "body" | "thought" | "feeling" | ""): PathLetter | null {
  if (seed.length < 12 || intention.trim().length < 4) return null;
  const question = intention.trim();
  const meet = bit(seed, "как встречает мир") || "ровно, без резкого перекоса";
  const feel = bit(seed, "как чувствует") || "ровно";
  const power = bit(seed, "куда тянется сила") || "к тому, что уже живо";
  const mind = bit(seed, "как думает") || "сначала ищет, как это назвать";
  const act = bit(seed, "как действует") || "не спеша";
  const edge = bit(seed, "как держит границу") || "через привычный ритм";
  const strong = bit(seed, "внутренняя опора") || "умение не бросать вопрос на первом неудобном месте";
  const thin = bit(seed, "тонкое место") || "спешка закрыть вопрос чужим ответом";
  const lens =
    channel === "body"
      ? "Ярче всего вопрос звучит в ощущениях тела, поэтому смотреть его полезно через тело, а не через объяснение."
      : channel === "thought"
        ? "Ярче всего вопрос звучит в мыслях, поэтому ему нужна одна ясная фраза, а не длинное рассуждение."
        : channel === "feeling"
          ? "Ярче всего вопрос звучит в эмоциях, поэтому сначала нужно назвать чувство, и только потом решать."
          : "Вопрос становится яснее там, где ты замечаешь первую живую реакцию, а не готовый вывод.";

  const tools =
    channel === "body"
      ? [
          "Перед тем как думать о вопросе, заметь, где в теле он отзывается, и побудь там четыре спокойных вдоха.",
          "Сделай один медленный телесный шаг — встать, пройтись, расправить плечи — и спроси, стало ли вопросу теснее.",
          "Запиши одно ощущение, без причины и без совета себе.",
          "Вечером вернись к этому месту в теле и ничего в нём не исправляй.",
        ]
      : channel === "thought"
        ? [
            "Напиши свой вопрос одной фразой, без объяснения «потому что».",
            "Вычеркни из неё всё, что звучит как оправдание, и оставь то, что осталось.",
            "Поймай мысль, которая повторяется, когда ты откладываешь этот вопрос.",
            "Ответь на неё двумя честными словами и на этом остановись.",
          ]
        : channel === "feeling"
          ? [
              "Назови чувство одним словом, не рассказывая историю вокруг него.",
              "Дай этому чувству минуту и не уговаривай его стать другим.",
              "Спроси, что оно бережёт в твоём вопросе.",
              "После этого выбери один маленький шаг на сегодня и сделай только его.",
            ]
          : [
              "Остановись на первой реакции, которая приходит к вопросу, и не подменяй её красивым выводом.",
              "Назови, где она живёт: в теле, в мысли или в чувстве.",
              "Запиши одну честную фразу оттуда, без совета себе.",
              "Сделай один маленький шаг, который эта фраза уже подсказывает.",
            ];

  return {
    temperament: `Внутренний уклад начинается с того, как ты встречаешь мир: ${meet}. Чувства при этом устроены так: ${feel}. Сила тянется туда, где ${power}. Думаешь ты так: ${mind}. Действуешь так: ${act}, а границу держишь через то, что ${edge}.`,
    prism: `Вопрос «${question}» ты видишь не нейтрально. Его окрашивает тот же уклад: что кажется срочным, что хочется отложить и где ты ждёшь себя другого. ${lens} Опора здесь — ${strong}. Истощает вопрос обычно через тонкое место: ${thin}.`,
    strength: `В этом вопросе уже помогает ${strong}. Это не приём со стороны, а способ, которым ты и так умеешь держаться. Пока ответ ещё не ясен, на эту опору можно встать, не дожидаясь вдохновения.`,
    shadow: `Мешает то, что связано с тонким местом: ${thin}. Там легко закрыть вопрос чужим объяснением или усталостью. Граница, которую ты держишь через «${edge}», в этом месте иногда становится стеной, а не опорой.`,
    tools,
    heart: `Для вопроса «${question}» не нужно становиться другим человеком. Нужное уже есть в том, как ты встречаешь мир, чувствуешь и действуешь. Вопрос, который истощал, может стать источником силы, если смотреть в него своим способом, а не чужим.`,
  };
}
