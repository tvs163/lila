export function personalNote(chart: InnerChart, lens: Lens): { note: string; form: string } {
  const tendency = TENDENCY[chart.moonNakshatra] ?? TENDENCY[0];
  return {
    note: `${tendency} ${LENS_WHY[lens]}`,
    form: FORM[chart.elements[lens]],
  };
}
